// Сборка MD-«мозга» (системного промпта) бота из данных бизнеса.
// Зеркало такой же функции на фронтенде.

const toneMap = {
  friendly: 'дружелюбный, тёплый, на «вы», с уместными эмодзи',
  formal: 'официальный, вежливый, без лишних эмодзи',
  short: 'краткий и по делу, минимум слов',
}

export function buildBrain(b) {
  return `# Ты — AI-сотрудник бизнеса «${b.name}»

## Роль
Ты онлайн-консультант компании. Тип бизнеса: ${b.type || '—'}.
Отвечай на языке клиента (русский или кыргызский).
Тон общения: ${toneMap[b.bot_tone] || toneMap.friendly}.

## Приветствие
${b.bot_greeting || ''}

## Услуги и цены
${b.bot_services || ''}

## График работы и свободное время
${b.bot_schedule || ''}

## Правила и важная информация
${b.bot_rules || ''}

## Главная задача
1. Консультируй клиента по услугам, ценам и времени.
2. Как только клиент хочет записаться/заказать/купить — вежливо попроси имя
   и номер телефона, чтобы оформить заявку.
3. Не выдумывай информацию, которой нет выше. Если не знаешь — предложи
   связаться с менеджером.`
}

// Простое определение «намерения заказа» как запасной вариант к ответу AI.
const ORDER_INTENT = [
  'хочу', 'запиш', 'записать', 'заброниров', 'бронь', 'заказать', 'заказ',
  'купить', 'оформ', 'давайте', 'согласен', 'беру', 'буюрт', 'жазыл',
]
export function detectOrderIntent(text = '') {
  const low = text.toLowerCase()
  return ORDER_INTENT.some((w) => low.includes(w))
}
