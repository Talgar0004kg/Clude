// Умный бот-симулятор для ДЕМО-режима (без бэкенда, работает на GitHub Pages).
// Отвечает на любой вопрос по MD-данным бизнеса: услуги, цены, время, адрес,
// приветствия, благодарности. Понимает русский и базовый кыргызский.
// На реальном бэкенде это место занимает DeepSeek с тем же MD-«мозгом».

const GREETING = ['салам', 'ассалам', 'привет', 'здравств', 'здаров', 'саламатсыз', 'кутман', 'hello', 'hi']
const THANKS = ['спасибо', 'рахмат', 'благодар', 'thanks']
const BYE = ['пока', 'до свидан', 'жакшы кал', 'bye']
const SERVICES_Q = ['услуг', 'что есть', 'что у вас', 'выбор', 'варианты', 'меню', 'кызмат', 'что предлаг', 'каталог', 'список']
const PRICE_Q = ['цена', 'цены', 'сколько', 'стоит', 'прайс', 'баа', 'канча', 'почём', 'почем']
const TIME_Q = ['время', 'график', 'когда', 'часы', 'свобод', 'окошк', 'убакыт', 'график', 'работаете', 'открыт']
const ADDR_Q = ['адрес', 'где', 'находит', 'дарек', 'кайда', 'как добрат', 'локац']
const ORDER_INTENT = [
  'хочу', 'запиш', 'записать', 'заброниров', 'бронь', 'заказать', 'заказ',
  'купить', 'оформ', 'давайте', 'согласен', 'беру', 'буюрт', 'жазыл', 'хотел бы',
  'можно записать', 'запишите',
]

function has(text, words) {
  const low = text.toLowerCase()
  return words.some((w) => low.includes(w))
}

// Возвращает { reply, intent }. intent === 'order' => показать анкету.
export function demoBotReply(business, history) {
  const last = history[history.length - 1]?.text || ''
  const b = business.bot
  const userMsgs = history.filter((m) => m.role === 'user').length

  // 1. Намерение заказа — приоритет
  if (has(last, ORDER_INTENT)) {
    return {
      reply: 'Отлично! 🎉 Чтобы оформить запись, подскажите, пожалуйста:\n— как к вам обращаться?\n— ваш номер телефона?',
      intent: 'order',
    }
  }

  // 2. Благодарность / прощание
  if (has(last, THANKS)) {
    return { reply: 'Пожалуйста! 🙌 Будут вопросы — пишите. Хотите записаться?', intent: null }
  }
  if (has(last, BYE)) {
    return { reply: 'Хорошего дня! 👋 Будем рады видеть вас снова.', intent: null }
  }

  // 3. Конкретные темы по MD-данным
  if (has(last, PRICE_Q)) {
    return { reply: `Вот наши услуги и цены:\n\n${b.services}\n\nЧто вас интересует? Могу записать. 📝`, intent: null }
  }
  if (has(last, SERVICES_Q)) {
    return { reply: `Конечно! Вот что мы предлагаем:\n\n${b.services}\n\nПо какой услуге подсказать подробнее?`, intent: null }
  }
  if (has(last, TIME_Q)) {
    return { reply: `${b.schedule}\n\nХотите, запишу вас на удобное время?`, intent: null }
  }
  if (has(last, ADDR_Q)) {
    return { reply: `${b.rules}\n\nЖдём вас! Записать на визит?`, intent: null }
  }

  // 4. Приветствие — тёплый ответ с кратким набором услуг
  if (has(last, GREETING) || userMsgs <= 1) {
    const firstLine = (b.services || '').split('\n')[0] || ''
    return {
      reply: `Здравствуйте! 😊 Рад помочь. Вот что у нас есть:\n\n${b.services}\n\nМогу рассказать про цены, свободное время или сразу записать вас. Что интересует?`,
      intent: null,
    }
  }

  // 5. Универсальный полезный ответ (вместо «общих слов»)
  return {
    reply: `Подскажу по любому вопросу. Вот наши услуги:\n\n${b.services}\n\n🕐 Время работы: ${(b.schedule || '').split('\n')[0]}\n📍 ${(b.rules || '').split('\n')[0]}\n\nХотите записаться? Напишите «хочу записаться».`,
    intent: null,
  }
}
